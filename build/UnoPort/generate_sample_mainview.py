"""
Generates samples/Uno/BehaviorsTestApplication/Views/MainView.xaml (the WinUI twin of the sample's main view) from
samples/BehaviorsTestApplication/Views/MainView.axaml.

Every Avalonia tab (`<TabItem Header="..."><pages:XView /></TabItem>`) becomes a sidebar `TabViewItem` with the same
header, in the same order. The tab hosts `<pages:XView />` when the page has a WinUI twin (`XView.xaml` anywhere under
samples/Uno/BehaviorsTestApplication/Views), otherwise a `PendingSampleView` placeholder showing the header, so pages
that are not ported yet never break the build.

Run it after adding or removing a page twin (the output is deterministic):

    python3 build/UnoPort/generate_sample_mainview.py          # rewrite MainView.xaml
    python3 build/UnoPort/generate_sample_mainview.py --check  # exit 1 when MainView.xaml is out of date
"""
import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
AVALONIA_MAIN_VIEW = os.path.join(ROOT, "samples", "BehaviorsTestApplication", "Views", "MainView.axaml")
UNO_PROJECT = os.path.join(ROOT, "samples", "Uno", "BehaviorsTestApplication")
UNO_MAIN_VIEW = os.path.join(UNO_PROJECT, "Views", "MainView.xaml")

TAB_ITEM = re.compile(
    r"<TabItem\s+Header=\"(?P<header>[^\"]*)\"\s*>\s*<pages:(?P<view>\w+)\s*/>\s*</TabItem>",
    re.S,
)

HEADER = """\
<!--
  Generated by build/UnoPort/generate_sample_mainview.py from samples/BehaviorsTestApplication/Views/MainView.axaml.
  Do not edit by hand: port a page (Views/Pages/XView.xaml) and run the script again (see samples/Uno/README.md).
  Pages without a WinUI twin are shown as a PendingSampleView.
-->
<UserControl x:Class="BehaviorsTestApplication.Views.MainView"
             xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"
             xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"
             xmlns:d="http://schemas.microsoft.com/expression/blend/2008"
             xmlns:mc="http://schemas.openxmlformats.org/markup-compatibility/2006"
             xmlns:i="using:Xaml.Interactivity"
             xmlns:ic="using:Xaml.Interactions.Core"
             xmlns:icustom="using:Xaml.Interactions.Custom"
             xmlns:controls="using:BehaviorsTestApplication.Controls"
             xmlns:pages="using:BehaviorsTestApplication.Views.Pages"
             mc:Ignorable="d" d:DesignWidth="1000" d:DesignHeight="700">
  <i:Interaction.Behaviors>
    <!-- The window behaviors of the Avalonia MainWindow (a WinUI Window is not a FrameworkElement). -->
    <ic:EventTriggerBehavior EventName="Loaded">
      <ic:InvokeCommandAction Command="{x:Bind ViewModel.InitializeCommand}" />
    </ic:EventTriggerBehavior>
    <icustom:DataContextChangedTrigger>
      <ic:InvokeCommandAction Command="{x:Bind ViewModel.DataContextChangedCommand}" />
    </icustom:DataContextChangedTrigger>
  </i:Interaction.Behaviors>
  <Grid>
    <Grid.RowDefinitions>
      <RowDefinition Height="Auto" />
      <RowDefinition Height="Auto" />
      <RowDefinition Height="*" />
    </Grid.RowDefinitions>
    <TextBox x:Name="SearchBox"
             Grid.Row="0"
             PlaceholderText="Search pages..."
             Margin="0,0,0,8">
      <i:Interaction.Behaviors>
        <icustom:FocusOnAttachedBehavior />
      </i:Interaction.Behaviors>
    </TextBox>
    <TextBlock x:Name="NoMatchesText"
               Grid.Row="1"
               Text="No pages match the search."
               Margin="0,0,0,8"
               Visibility="Collapsed" />
    <!-- Avalonia: TabControl.sidebar (SideBar.axaml); WinUI: a TabView re-templated as a vertical sidebar (SideBar.xaml). -->
    <controls:SingleSelectionTabControl x:Name="PagesTabControl"
                                        Grid.Row="2"
                                        SelectedIndex="0"
                                        Style="{StaticResource SidebarTabViewStyle}">
      <i:Interaction.Behaviors>
        <icustom:SelectingItemsControlSearchBehavior SearchBox="{x:Bind SearchBox}"
                                                     NoMatchesControl="{x:Bind NoMatchesText}"
                                                     EnableSorting="True"
                                                     SortOrder="Ascending" />
      </i:Interaction.Behaviors>
      <controls:SingleSelectionTabControl.TabItems>
"""

FOOTER = """\
      </controls:SingleSelectionTabControl.TabItems>
    </controls:SingleSelectionTabControl>
  </Grid>
</UserControl>
"""


def ported_views():
    views = set()
    for root, dirs, files in os.walk(os.path.join(UNO_PROJECT, "Views")):
        dirs[:] = [d for d in dirs if d not in ("bin", "obj")]
        for name in files:
            if name.endswith(".xaml"):
                views.add(name[: -len(".xaml")])
    return views


def generate():
    with open(AVALONIA_MAIN_VIEW, encoding="utf-8-sig") as f:
        source = f.read()
    tabs = [(m.group("header"), m.group("view")) for m in TAB_ITEM.finditer(source)]
    expected = source.count("<TabItem ")
    if len(tabs) != expected:
        raise SystemExit(f"parsed {len(tabs)} of {expected} TabItems in {AVALONIA_MAIN_VIEW}; update TAB_ITEM")

    ported = ported_views()
    lines = [HEADER]
    for header, view in tabs:
        lines.append(f'        <TabViewItem Header="{header}" Style="{{StaticResource SidebarTabViewItemStyle}}">\n')
        if view in ported:
            lines.append(f"          <pages:{view} />\n")
        else:
            lines.append(f'          <controls:PendingSampleView Header="{header}" />\n')
        lines.append("        </TabViewItem>\n")
    lines.append(FOOTER)
    count = sum(1 for _, view in tabs if view in ported)
    return "".join(lines), len(tabs), count


def main(args):
    text, total, ported = generate()
    current = None
    if os.path.exists(UNO_MAIN_VIEW):
        with open(UNO_MAIN_VIEW, encoding="utf-8") as f:
            current = f.read()
    if "--check" in args:
        if current != text:
            print(f"{os.path.relpath(UNO_MAIN_VIEW, ROOT)} is out of date; run {os.path.relpath(__file__, ROOT)}")
            return 1
        print(f"up to date: {ported} of {total} pages ported")
        return 0
    if current != text:
        with open(UNO_MAIN_VIEW, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print(f"{os.path.relpath(UNO_MAIN_VIEW, ROOT)}: {total} tabs, {ported} ported, {total - ported} pending")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
